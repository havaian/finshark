// Click (click.uz) payment integration - SHOP API.
//
// Flow (both payment buttons share this exact backend path):
//   1. User picks a plan -> POST /api/billing/click/orders creates a
//      click_orders row in status='created' with a generated merchant_trans_id.
//      NO subscription exists yet.
//   2. The frontend either redirects to my.click.uz/services/pay/ (button 1) or
//      opens the checkout.js overlay (button 2). Both carry the same
//      merchant_trans_id.
//   3. Click calls Prepare (action=0) on our server. We verify the MD5 sign,
//      check the order + amount, move it to status='prepared' and return a
//      merchant_prepare_id drawn from click_merchant_prepare_id_seq.
//   4. Click calls Complete (action=1). On error=0 we move the order to
//      status='paid' and grant the subscription. On error<0 we cancel.
//   5. Fiscalization (OFD) runs after Complete against Click's Merchant API,
//      keyed on click_paydoc_id. It is deliberately decoupled: a fiscal failure
//      never unwinds a successful payment, it just leaves fiscal_status='failed'
//      for the retry cron / admin re-fire.
//
// merchant_prepare_id comes from a dedicated sequence rather than the order's
// uuid because Click types it as an int and echoes it back verbatim in the
// Complete request. Reusing a numeric sequence keeps that round-trip lossless.
//
// This migration also decommissions the P2P (card-transfer) flow: every
// payment_cards row is deactivated so nothing is displayed to users. The
// payment_cards / payment_submissions TABLES ARE DEPRECATED BUT KEPT - they
// hold the historical record of who paid what before Click, which is needed for
// accounting and dispute handling. The admin panel keeps a read-only view of
// them. Dropping them is a separate, deliberate decision.

exports.shorthands = undefined;

exports.up = (pgm) => {
  // gen_random_uuid(). Already enabled by the billing-core migration; the
  // IF NOT EXISTS keeps this safe if ordering ever changes.
  pgm.sql('CREATE EXTENSION IF NOT EXISTS pgcrypto');

  // -- enums -----------------------------------------------------------------
  // created   -> order row exists, user has not paid yet
  // prepared  -> Click's Prepare succeeded, awaiting Complete
  // paid      -> Complete succeeded, subscription granted
  // cancelled -> Complete arrived with error < 0, or we rejected it
  // failed    -> our own processing blew up after a successful charge; needs
  //              manual reconciliation (logged loudly, surfaced in admin)
  pgm.createType('click_order_status', [
    'created',
    'prepared',
    'paid',
    'cancelled',
    'failed',
  ]);

  // not_required -> fiscalization disabled by config at the time of payment
  // pending      -> paid, fiscal receipt not yet submitted
  // submitted    -> OFD accepted the receipt
  // failed       -> submission rejected/errored; retry cron + admin re-fire
  pgm.createType('click_fiscal_status', [
    'not_required',
    'pending',
    'submitted',
    'failed',
  ]);

  // -- merchant_prepare_id sequence -----------------------------------------
  // Click types merchant_prepare_id as int and echoes it back in Complete. We
  // hand out values from here at Prepare time and match on them at Complete.
  pgm.createSequence('click_merchant_prepare_id_seq', {
    start: 1,
    increment: 1,
  });

  // -- click_orders ----------------------------------------------------------
  pgm.createTable('click_orders', {
    id: { type: 'uuid', primaryKey: true, default: pgm.func('gen_random_uuid()') },
    user_id: { type: 'bigint', notNull: true, references: 'users(id)', onDelete: 'CASCADE' },
    // RESTRICT mirrors subscriptions.plan_id - don't allow deleting a plan that
    // has orders pointing at it.
    plan_id: { type: 'text', notNull: true, references: 'plans(id)', onDelete: 'RESTRICT' },

    // What Click sees and echoes back in every callback. Opaque, generated by
    // the service. UNIQUE because Click keys the whole payment on it.
    merchant_trans_id: { type: 'text', notNull: true },

    // Amount snapshotted from the plan at order-create time (plans.price_minor
    // can change later). Minor units (tiyin), same as plans / subscriptions.
    amount_minor: { type: 'integer', notNull: true },
    currency: { type: 'text', notNull: true },

    status: { type: 'click_order_status', notNull: true, default: 'created' },

    // Click-side identifiers, filled in as the callbacks arrive.
    click_trans_id: { type: 'bigint' },      // payment attempt id
    click_paydoc_id: { type: 'bigint' },     // payment id; shown to the user in SMS,
                                             // and the key fiscalization is filed under
    merchant_prepare_id: { type: 'bigint' }, // ours, from the sequence above
    merchant_confirm_id: { type: 'bigint' }, // ours, returned at Complete

    // Last error Click reported (Complete carries error/error_note on cancel).
    error_code: { type: 'integer' },
    error_note: { type: 'text' },

    // Set when a successful Complete grants premium.
    subscription_id: { type: 'uuid', references: 'subscriptions(id)', onDelete: 'SET NULL' },

    // -- fiscalization ------------------------------------------------------
    fiscal_status: { type: 'click_fiscal_status', notNull: true, default: 'pending' },
    fiscal_attempts: { type: 'integer', notNull: true, default: 0 },
    fiscal_last_error: { type: 'text' },
    fiscal_qr_url: { type: 'text' },          // ofd.soliq.uz receipt URL, once known
    fiscal_submitted_at: { type: 'timestamptz' },

    prepared_at: { type: 'timestamptz' },
    paid_at: { type: 'timestamptz' },
    cancelled_at: { type: 'timestamptz' },

    metadata: { type: 'jsonb', notNull: true, default: pgm.func(`'{}'::jsonb`) },
    created_at: { type: 'timestamptz', notNull: true, default: pgm.func('NOW()') },
    updated_at: { type: 'timestamptz', notNull: true, default: pgm.func('NOW()') },
  });

  pgm.addConstraint('click_orders', 'chk_click_orders_amount_positive', {
    check: 'amount_minor > 0',
  });

  // Click keys the payment on merchant_trans_id, so it must be unique for the
  // Prepare lookup to be unambiguous.
  pgm.createIndex('click_orders', 'merchant_trans_id', {
    name: 'uq_click_orders_merchant_trans_id',
    unique: true,
  });

  // A given Click transaction attempt maps to at most one order. Partial so the
  // many NULLs (orders never paid) don't collide.
  pgm.createIndex('click_orders', 'click_trans_id', {
    name: 'uq_click_orders_click_trans_id',
    unique: true,
    where: 'click_trans_id IS NOT NULL',
  });

  // Complete echoes merchant_prepare_id back; we look the order up by it as a
  // cross-check against merchant_trans_id.
  pgm.createIndex('click_orders', 'merchant_prepare_id', {
    name: 'idx_click_orders_merchant_prepare_id',
    where: 'merchant_prepare_id IS NOT NULL',
  });

  // "My orders", newest first (the return page polls by id, but the user's
  // payment history lists by user).
  pgm.createIndex('click_orders', ['user_id', { name: 'created_at', sort: 'DESC' }], {
    name: 'idx_click_orders_user_created',
  });

  // Admin queue: filter by status, newest first.
  pgm.createIndex('click_orders', ['status', { name: 'created_at', sort: 'DESC' }], {
    name: 'idx_click_orders_status_created',
  });

  // Drives the fiscal retry sweep - a tiny partial index so the cron's scan
  // stays cheap no matter how many orders accumulate.
  pgm.createIndex('click_orders', ['fiscal_status', 'created_at'], {
    name: 'idx_click_orders_fiscal_retry',
    where: `status = 'paid' AND fiscal_status IN ('pending', 'failed')`,
  });

  // -- click_callback_log ----------------------------------------------------
  // Click's integration checklist asks for request/response logging on both
  // callback endpoints so their support team can debug failed payments. This
  // table is that log. It is append-only and deliberately stores the RAW body
  // (post-parse, pre-validation) so a malformed request is still recorded.
  //
  // No card data ever reaches these endpoints - Click's callbacks carry only
  // transaction ids, an amount and a signature - so there is no PAN/PCI
  // exposure in keeping the full payload.
  pgm.createTable('click_callback_log', {
    id: { type: 'bigserial', primaryKey: true },
    // Nullable: a request for an unknown merchant_trans_id, or one that fails
    // signature verification, still gets logged with no order attached.
    order_id: { type: 'uuid', references: 'click_orders(id)', onDelete: 'SET NULL' },
    // 0 = Prepare, 1 = Complete. Nullable when the body was unparsable.
    action: { type: 'integer' },
    click_trans_id: { type: 'bigint' },
    merchant_trans_id: { type: 'text' },
    request_body: { type: 'jsonb', notNull: true, default: pgm.func(`'{}'::jsonb`) },
    request_headers: { type: 'jsonb', notNull: true, default: pgm.func(`'{}'::jsonb`) },
    response_body: { type: 'jsonb' },
    // The error code WE returned to Click (0 = accepted, negative = rejected).
    error_code: { type: 'integer' },
    // Short machine-readable reason, e.g. 'ok', 'bad_sign', 'amount_mismatch'.
    verdict: { type: 'text' },
    ip: { type: 'text' },
    created_at: { type: 'timestamptz', notNull: true, default: pgm.func('NOW()') },
  });

  pgm.createIndex('click_callback_log', ['order_id', { name: 'created_at', sort: 'DESC' }], {
    name: 'idx_click_log_order_created',
  });
  pgm.createIndex('click_callback_log', [{ name: 'created_at', sort: 'DESC' }], {
    name: 'idx_click_log_created',
  });

  // -- plans.fiscal_item_name ------------------------------------------------
  // The receipt line printed on the OFD fiscal check for this plan. Must end
  // with the unit, per the OFD item spec (e.g. "Finshark Premium 30 kun, 1
  // dona"). Nullable: fiscalization refuses to submit an order whose plan has
  // no name configured rather than inventing one, and the admin plan editor
  // surfaces it as a required field once fiscalization is switched on.
  pgm.addColumn('plans', {
    fiscal_item_name: { type: 'text' },
  });

  // -- updated_at trigger (set_updated_at() lives in content_and_srs.js) -----
  pgm.sql(`
    CREATE TRIGGER trg_click_orders_updated_at
      BEFORE UPDATE ON click_orders
      FOR EACH ROW EXECUTE FUNCTION set_updated_at();
  `);

  // -- decommission the P2P card-transfer flow -------------------------------
  // Deactivate every receiving card so nothing is shown to users even if a
  // stale frontend build is still deployed. Rows are kept for the historical
  // record; the user-facing endpoints are removed in the same release.
  pgm.sql(`UPDATE payment_cards SET is_active = FALSE WHERE is_active = TRUE`);
};

